#!/usr/bin/env python3
"""Regenerate fe-testing/report/safety-tag-audit.md.

    python3 safety_tag_audit.py                      # writes the default path
    python3 safety_tag_audit.py --out - | less       # stdout

WHY THIS EXISTS
The audit doc claimed "Generated by mutation_tags.py. Regenerate rather than
hand-editing" — but mutation_tags.py is a library with no CLI and no report code, so
there was no way to regenerate anything. The table went stale (it still read 1812
tests / 813 mutating / 999 readonly against a suite that had moved to 860/765) and the
only remaining option was the hand-editing the doc forbade. This script is that
missing half.

WHAT IT ADDS OVER A HEADCOUNT
A MISMATCH column: the tag actually written in the file vs the verdict
mutation_tags.classify_source derives from the test body. A mismatch means someone
hand-picked a tag, or the body changed after the tag was generated — and a wrong
`@readonly` is invisible until it writes into an environment that was promised no
writes. That column is the reason to run this rather than trust the numbers.

It is a STATIC classifier, so it cannot see an indirect write (a read-only screen
whose control POSTs, an audit row written on view). Proving those needs a run.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mutation_tags import classify_source  # noqa: E402

# Kept in sync with AREA_TAGS in fe-testing/scripts/lint-tests.mjs (lint rule R9).
AREA_TAGS = [
    '@actors', '@analytics', '@channel', '@drtp', '@forge',
    '@governance', '@operations', '@releases', '@sop', '@strategy',
]

REPO = Path(__file__).resolve().parents[4]
SUITE = REPO / 'apps' / 'testing' / 'automation-testing' / 'fe-testing'
TEST_DECL = re.compile(r"^\s*test(?:\.(?:skip|fail|fixme|only))?\(\s*['\"`]")


def parked_files(config: Path) -> set[str]:
    """Basenames playwright.config.ts drops from collection (`testIgnore`)."""
    if not config.exists():
        return set()
    m = re.search(r'testIgnore:\s*\[(.*?)\]', config.read_text(encoding='utf-8'), re.S)
    return set(re.findall(r"['\"]([^'\"]+)['\"]", m.group(1))) if m else set()


def area_tag_of(src: str) -> str:
    """The area tag on the file's top-level describes. '' when absent, '+' when split."""
    found = []
    lines = src.split('\n')
    for i, ln in enumerate(lines):
        if not ln.startswith('test.describe('):
            continue
        decl = ln + '\n' + (lines[i + 1] if i + 1 < len(lines) else '')
        if '@smoke' in decl and not any(t in decl for t in AREA_TAGS):
            found.append('@smoke')
        found += [t for t in AREA_TAGS if t in decl]
    uniq = sorted(set(found))
    return '+'.join(uniq) if uniq else ''


def audit_file(path: Path) -> dict:
    src = path.read_text(encoding='utf-8')
    verdicts = {i: v for i, v, _ in classify_source(src)}
    signals: set[str] = set()
    for _, v, sg in classify_source(src):
        if v == 'mutating':
            signals |= {s for s in sg if not s.startswith('via:')}

    ro = mu = untagged = mismatch = 0
    for i, ln in enumerate(src.split('\n')):
        if not TEST_DECL.match(ln):
            continue
        # WHOLE line, never a prefix window: a 400-char slice missed two tests whose
        # titles are long enough to push the tag past it, and reported them as untagged.
        written = '@readonly' if '@readonly' in ln else '@mutating' if '@mutating' in ln else ''
        if written == '@readonly':
            ro += 1
        elif written == '@mutating':
            mu += 1
        else:
            untagged += 1
        derived = verdicts.get(i)
        # Only a written @readonly over a `mutating` verdict is worth flagging. The
        # reverse (@mutating over `readonly`) is the safe direction and is often
        # deliberate — a test kept out of a readonly run on purpose.
        if written == '@readonly' and derived == 'mutating':
            mismatch += 1

    return {
        'file': path.name,
        'tests': ro + mu + untagged,
        'readonly': ro,
        'mutating': mu,
        'untagged': untagged,
        'mismatch': mismatch,
        'area': area_tag_of(src),
        'why': ', '.join(sorted(signals)) or '—',
    }


def render(rows: list[dict], parked: set[str]) -> str:
    live = [r for r in rows if r['file'] not in parked]
    t = sum(r['tests'] for r in live)
    ro = sum(r['readonly'] for r in live)
    mu = sum(r['mutating'] for r in live)
    un = sum(r['untagged'] for r in live)
    mis = sum(r['mismatch'] for r in live)

    out = [
        '# Safety-tag audit — @readonly / @mutating',
        '',
        'Every test in `fe-testing/script/ui` carries exactly one of `@readonly` / `@mutating`,',
        'so a run against production (or any tenant that is not our own test tenant) can select',
        'the non-writing subset. `playwright.config.ts` applies that selection ITSELF — it adds',
        '`grep: /@readonly/` whenever the resolved data mode is readonly — so the tag is not a',
        'convention someone has to remember to use on the command line.',
        '',
        'Regenerate with `python3 .claude/skills/ui-flow-test-generator/scripts/safety_tag_audit.py`.',
        'Two gates back it up: `lint:tests` R7 fails a missing or doubled safety tag, and R9 fails',
        'a top-level describe with no area tag.',
        '',
        f'**{t} tests in collected specs — {mu} @mutating, {ro} @readonly'
        + (f', {un} UNTAGGED' if un else '') + '.**',
        '',
        f'**Tag-vs-body mismatches: {mis}.**'
        + ('' if mis else ' Nothing is tagged `@readonly` over a body the classifier reads as writing.'),
        '',
        '> Counts are code sites. `--grep @readonly` reports slightly more: a few tests are',
        '> generated inside a loop and share one site, and the `setup`/`seed` projects join any',
        '> run as dependencies of `UI Tests`.',
        '>',
        '> The classifier is STATIC. It sees `click-write` / `api-write` / `seed` call shapes, not',
        '> an indirect write — a read-only screen whose control POSTs, or a row written on view.',
        '> A clean mismatch column is therefore necessary, not sufficient. Measured live on',
        '> 2026-09-07 across 9 spec files (336 `@readonly` tests): no real write, and the only',
        '> POST seen was `/api/realtime/negotiate`, the SignalR handshake, on every page load.',
        '',
        '## Collected specs',
        '',
        '| file | area | tests | @mutating | @readonly | mismatch | why mutating |',
        '|---|---|---:|---:|---:|---:|---|',
    ]
    # A file whose describe is commented out is not parked but contributes nothing. It
    # would otherwise read as an R9 violation (no area tag) when there is no live
    # describe to carry one.
    for r in sorted(live, key=lambda r: r['file']):
        area = r['area'] or ('_commented out_' if r['tests'] == 0 else '**NO AREA TAG**')
        out.append(f"| `{r['file']}` | {area} | {r['tests']} | {r['mutating']} "
                   f"| {r['readonly']} | {r['mismatch'] or '—'} | {r['why']} |")

    skipped = [r for r in rows if r['file'] in parked]
    if skipped:
        out += [
            '',
            '## Parked (`testIgnore` in playwright.config.ts)',
            '',
            'Not collected, so not part of the totals above. Listed because the tags still have to',
            'be right on the day a suite is un-parked.',
            '',
            '| file | area | tests | @mutating | @readonly | mismatch |',
            '|---|---|---:|---:|---:|---:|',
        ]
        for r in sorted(skipped, key=lambda r: r['file']):
            area = r['area'] or ('_commented out_' if r['tests'] == 0 else '**NO AREA TAG**')
            out.append(f"| `{r['file']}` | {area} | {r['tests']} | "
                       f"{r['mutating']} | {r['readonly']} | {r['mismatch'] or '—'} |")
    return '\n'.join(out) + '\n'


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--spec-dir', default=str(SUITE / 'script' / 'ui'))
    ap.add_argument('--config', default=str(SUITE / 'playwright.config.ts'))
    ap.add_argument('--out', default=str(SUITE / 'report' / 'safety-tag-audit.md'),
                    help="'-' for stdout")
    args = ap.parse_args()

    spec_dir = Path(args.spec_dir)
    files = sorted(spec_dir.glob('*.spec.ts'))
    if not files:
        print(f'safety_tag_audit: no *.spec.ts under {spec_dir}', file=sys.stderr)
        return 2

    rows = [audit_file(f) for f in files]
    text = render(rows, parked_files(Path(args.config)))

    if args.out == '-':
        sys.stdout.write(text)
    else:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding='utf-8')
        print(f'safety_tag_audit: wrote {out} ({len(files)} spec files)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
