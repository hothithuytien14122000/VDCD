"""Upsert a feature's seed recipes into the single shared registry.

Reads the `seed_recipes:` block from `--spec-yaml` and merges it into
`setup/seed-recipes.generated.ts` under the feature key (derived from the spec
filename). It does NOT create a per-feature TypeScript file — the generic engine
lives once in `setup/seed-runtime.ts`, and every feature shares it.

A spec opts in with:
    import { seedTest, expect } from '../../setup/seed-recipes.generated';
    const test = seedTest('<feature>');
then reads seeded ids via the `seedData` fixture: `({ page, seedData }) => …`.

If the spec has no `seed_recipes:` block (or it is empty / explicitly null),
the script exits 0 with a "No seed_recipes — skipping" message — this lets
SKILL.md call it unconditionally without a guard.

CLI:
    python3 generate_seed_fixture.py --spec-yaml <path> [--registry <path>]

Default --registry is `setup/seed-recipes.generated.ts`.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    print("pyyaml not installed. Run: pip install pyyaml", file=sys.stderr)
    sys.exit(2)


# ── Helpers ───────────────────────────────────────────────────────────────────

def _derive_feature(spec_path: Path) -> str:
    """`.../decision-recording-spec.yaml` -> `decision-recording`."""
    stem = spec_path.stem
    if stem.endswith("-spec"):
        stem = stem[: -len("-spec")]
    return stem


def _has_seed_block(data: dict) -> bool:
    block = data.get("seed_recipes")
    if not block or not isinstance(block, dict):
        return False
    # Treat fully-empty recipe block (no cleanup AND no seeds) as absent.
    if not block.get("cleanup") and not block.get("seeds"):
        return False
    return True


_REGISTRY_RE = re.compile(
    r"/\* @recipes-registry-begin \*/.*?/\* @recipes-registry-end \*/",
    re.DOTALL,
)
# Pull the object literal out of `const REGISTRY...= { … };` inside the markers.
_REGISTRY_JSON_RE = re.compile(r"=\s*(\{.*\})\s*;", re.DOTALL)


def _load_registry(registry_path: Path) -> dict:
    """Parse the existing REGISTRY object literal (valid JSON) → dict. {} if absent."""
    if not registry_path.exists():
        return {}
    text = registry_path.read_text(encoding="utf-8")
    block = _REGISTRY_RE.search(text)
    if not block:
        return {}
    m = _REGISTRY_JSON_RE.search(block.group(0))
    if not m:
        return {}
    try:
        return json.loads(m.group(1))
    except json.JSONDecodeError:
        print(
            f"WARNING: could not parse existing registry in {registry_path}; "
            "starting fresh (existing entries will be overwritten).",
            file=sys.stderr,
        )
        return {}


def _normalize_recipes(block: dict) -> dict:
    """Keep only the fields the runtime consumes; drop nulls for a clean diff."""
    return {
        "cleanup": block.get("cleanup") or [],
        "seeds": block.get("seeds") or [],
    }


# ── File emitter ──────────────────────────────────────────────────────────────

def emit_registry_file(registry: dict) -> str:
    # Stable key order keeps the generated diff minimal across runs.
    ordered = {k: registry[k] for k in sorted(registry)}
    registry_json = json.dumps(ordered, indent=2)

    return f"""// AUTO-GENERATED by generate_seed_fixture.py — DO NOT EDIT BY HAND.
// Single registry of seed recipes, keyed by feature. The generator upserts ONE
// feature key per run; it never creates a new file. The shared engine lives in
// `seed-runtime.ts`.
//
// Usage in a spec (real-mode opt-in):
//   import {{ seedTest, expect }} from '../../setup/seed-recipes.generated';
//   const test = seedTest('decision-recording');
//   test('…', async ({{ page, seedData }}) => {{ … seedData.objectiveId … }});

import {{ makeSeedTest, type Recipe, type CleanupRecipe }} from './seed-runtime';

type FeatureRecipes = {{ cleanup: CleanupRecipe[]; seeds: Recipe[] }};

/* @recipes-registry-begin */
const REGISTRY: Record<string, FeatureRecipes> = {registry_json};
/* @recipes-registry-end */

/** Build a Playwright `test` pre-wired with the recipes for `feature`. */
export function seedTest(feature: string) {{
  const r = REGISTRY[feature];
  if (!r) {{
    throw new Error(
      `[seed] no recipes registered for feature "${{feature}}". ` +
      `Run generate_seed_fixture.py on its spec, or check the feature key.`,
    );
  }}
  return makeSeedTest(r.cleanup ?? [], r.seeds ?? []);
}}

export {{ expect }} from './seed-runtime';
"""


# ── Main ──────────────────────────────────────────────────────────────────────

def main() -> int:
    p = argparse.ArgumentParser(
        description="Upsert a feature's seed recipes into the shared registry."
    )
    p.add_argument("--spec-yaml", required=True, help="Path to {feature}-spec.yaml")
    p.add_argument(
        "--registry",
        default="setup/seed-recipes.generated.ts",
        help="Path to the single shared registry file.",
    )
    # Back-compat: older SKILL.md passed --out setup/seed-{feature}.ts. Accept and
    # ignore it so existing call sites don't break; everything goes to --registry.
    p.add_argument("--out", default=None, help=argparse.SUPPRESS)
    args = p.parse_args()

    spec_path = Path(args.spec_yaml)
    if not spec_path.exists():
        print(f"Spec file not found: {spec_path}", file=sys.stderr)
        return 1

    with open(spec_path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}

    if not _has_seed_block(data):
        print("No seed_recipes — skipping")
        return 0

    feature = _derive_feature(spec_path)
    registry_path = Path(args.registry)
    registry_path.parent.mkdir(parents=True, exist_ok=True)

    registry = _load_registry(registry_path)
    recipes = _normalize_recipes(data["seed_recipes"])
    action = "Updated" if feature in registry else "Added"
    registry[feature] = recipes

    registry_path.write_text(emit_registry_file(registry), encoding="utf-8")
    print(
        f"{action} '{feature}' in {registry_path} "
        f"({len(recipes['seeds'])} seeds, {len(recipes['cleanup'])} cleanup rules; "
        f"{len(registry)} feature(s) total)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
